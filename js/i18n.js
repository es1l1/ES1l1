let lang = "en";

export function getLang() {
  return lang;
}

export function isRTL() {
  return lang === "ar";
}

export function t(key, vars) {
  const table = dict[lang] || dict.en;
  let value = table[key];
  if (value === undefined) value = dict.en[key];
  if (value === undefined) return key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function raw(key) {
  return t(key);
}

function applyOne(el) {
  const key = el.dataset.i18n;
  if (key) el.textContent = t(key);
  const placeholder = el.dataset.i18nPlaceholder;
  if (placeholder) el.setAttribute("placeholder", t(placeholder));
  const aria = el.dataset.i18nAria;
  if (aria) el.setAttribute("aria-label", t(aria));
  const title = el.dataset.i18nTitle;
  if (title) el.setAttribute("title", t(title));
}

export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n], [data-i18n-placeholder], [data-i18n-aria], [data-i18n-title]").forEach(applyOne);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("is-rtl", lang === "ar");
  document.title = t("brand.sub") + " — ES1l1";
}

const listeners = new Set();

export function onLanguageChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function setLang(next, { persist = true } = {}) {
  if (!dict[next]) next = "en";
  lang = next;
  if (persist) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage may be blocked */ }
  }
  applyTranslations();
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
  listeners.forEach((fn) => fn(lang));
}

export function initLanguage() {
  let saved = null;
  try { saved = localStorage.getItem(STORAGE_KEY); } catch { /* ignore */ }
  if (saved && dict[saved]) {
    setLang(saved, { persist: false });
  } else {
    const browser = (navigator.language || "en").toLowerCase();
    setLang(browser.startsWith("ar") ? "ar" : "en", { persist: false });
  }
}
